import re
from ml.schemas import ClarifyResponse
from ml.llm_client import llm_client

ANALYZER_SYSTEM_PROMPT = """
Ты — Навык «Аналитик образовательных программ АЦР» (GigaCowork Skill #1).
Твоя задача — проанализировать запрос методиста и текст приложенных референсов.

ПРАВИЛА ВЫБОРА ШАБЛОНА АЦР:
1. Шаблон "dpp_pk" (Дополнительная профессиональная программа повышения квалификации / стажировка):
   - Опирается на 273-ФЗ и Приказ Минобрнауки № 499.
   - Выбирается, если в запросе есть слова: «повышение квалификации», «ДПП», «стажировка», «удостоверение», «профстандарт», «для сотрудников / специалистов», либо объем программы >= 72 часов.
2. Шаблон "doop" (Дополнительная общеобразовательная общеразвивающая программа):
   - Опирается на 273-ФЗ и Приказ Минпросвещения № 629.
   - Выбирается, если в запросе есть слова: «интенсив», «общеразвивающая», «хакатон», «сертификат», «для широкой аудитории / школьников / начинающих без требований к диплому», либо объем 16–48 часов.

ПРАВИЛА ПРОВЕРКИ ПОЛНОТЫ ЗАПРОСА:
Проверь, понятны ли из запроса:
- Тема / ИТ-направление курса
- Объем в академических часах
- Целевая аудитория и входной уровень
- Форма обучения и итоговой аттестации

Верни JSON строго со следующей структурой:
{
  "is_complete": true/false,
  "template_type": "dpp_pk" или "doop",
  "template_reason": "Краткое объяснение выбора шаблона и нормативной базы",
  "extracted_params": {
    "topic": "...",
    "total_hours": число,
    "target_audience": "...",
    "education_form": "...",
    "ia_form": "..."
  },
  "clarifying_questions": ["Вопрос 1...", "Вопрос 2..."]
}
"""


def analyze_user_request(user_query: str, reference_text: str = "") -> ClarifyResponse:
    # Быстрая эвристика для fallback-режима (и предзаполнения)
    hours_match = re.search(r"(\d+)\s*(?:час|ч\b|ак\.?\s*ч)", user_query.lower())
    extracted_hours = int(hours_match.group(1)) if hours_match else 72

    is_doop = any(w in user_query.lower() for w in ["интенсив", "общеразвивающ", "сертификат", "хакатон", "дооп"]) or extracted_hours < 36
    tpl_type = "doop" if is_doop else "dpp_pk"
    tpl_reason = (
        "Выбран шаблон ДООП (Приказ Минпросвещения РФ № 629, выдается Сертификат), так как запрошен практический интенсив / общеразвивающий формат."
        if is_doop else
        "Выбран шаблон ДПП Повышения квалификации (Приказ Минобрнауки РФ № 499 и 273-ФЗ, выдается Удостоверение о ПК с привязкой к профстандартам Минтруда)."
    )

    # Проверяем, нужно ли задать уточняющие вопросы
    questions = []
    if not hours_match:
        questions.append("Какой точный объем программы в академических часах требуется (например: 24, 72, 144 или 248 ч.)?")
    if not any(w in user_query.lower() for w in ["для ", "сотрудник", "специалист", "студент", "аналитик", "разработчик", "учител", "госслуж", "слушател"]):
        questions.append("Кто является целевой аудиторией курса и какой у них стартовый уровень подготовки?")
    if not any(w in user_query.lower() for w in ["аттестац", "проект", "экзамен", "зачет", "зачёт", "тест", "хакатон"]):
        questions.append("В какой форме планируется итоговая аттестация (защита проекта, итоговое тестирование, зачёт в форме хакатона)?")

    fallback = {
        "is_complete": len(questions) == 0,
        "template_type": tpl_type,
        "template_reason": tpl_reason,
        "extracted_params": {
            "topic": user_query[:120],
            "total_hours": extracted_hours,
            "target_audience": "Специалисты с базовыми навыками работы с данными и ИТ-системами" if not is_doop else "Взрослые от 18 лет, заинтересованные в создании ИИ-продуктов",
            "education_form": "Очно-заочная с применением ЭО и ДОТ",
            "ia_form": "Защита итогового проекта (зачёт)" if not is_doop else "Защита командного проекта в формате хакатона"
        },
        "clarifying_questions": questions
    }

    prompt = f"ЗАПРОС МЕТОДИСТА:\n{user_query}\n\nТЕКСТ РЕФЕРЕНСОВ:\n{reference_text[:3000]}"
    result_dict = llm_client.generate_json(ANALYZER_SYSTEM_PROMPT, prompt, fallback_data=fallback)
    return ClarifyResponse(**result_dict)